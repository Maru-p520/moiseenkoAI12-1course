print("=== Добро пожаловать в Кулинарный калькулятор ===")
while True:
    print("=== Меню операций ===")
    print("1. Объединеие ингридиентов (сложение)")
    print("2. Убрать часть продукта (вычитание)")
    print("3. Увеличить порцию (умножение)")
    print("4. Разделить на порции (деление)")
    print("5. Маштабирование (возведение в степень)")
    print("6. Остаток продуктов (деление с остатком)")
    print("7. Целые порции (деление на цело)")
    print("0. Выход")
    choice = int(input("Выберите операцию (0-7):"))
    if choice == 0: # Выход
        print("Программа завершена. Приятного аппетита:)")
        break
    elif 1 <= choice <= 7: 
        num1 = float(input("Введите первое число: "))
        num2 = float(input("Ввеите второе число: "))
# 1. Сложение
    if choice == 1:
        result = num1 + num2 
        print(f"Сумма: {result}")
        if result > 12: # Доп. условие
            print("Внимание: Получится большая порция блюда!")
# 2. Вычитание
    if choice == 2:
        result = num1 - num2 
        print(f"Разница: {result}")
        if result > 12: # Доп. условие
            print("Внимание: Получится большая порция блюда!")
# 3. Умножение
    if choice == 3:
        result = num1 * num2 
        print(f"Произведение: {result}") 
        if result > 12:
            print("Внимание: Получится большая порция блюда!")
# 4. Деление  
    if choice == 4:
        if num2 != 0:  # Проверка деления на ноль
            result = num1 / num2 
            print(f"Частное: {result}")    
            if result > 12: # Доп. условие
                print("Внимание: Получится большая порция блюда!")
        else:
            print("Ошибка: на ноль делить нельзя")  
# 5. Возведение в степенб
    if choice == 5:
        result = num1 ** num2 
        print(f"Степень: {result}") 
        if result > 12: # Доп. условие
            print("Внимание: Получится большая порция блюда!")
# 6.  Деление с остатком
    if choice == 6:
        if num2 != 0: # Проверка деления на ноль
            result = num1 % num2 
            print(f"Остаток: {result}")   
            if result > 12: # Доп. условие
                print("Внимание: Получится большая порция блюда!")
        else:
            print("Ошибка: на ноль делить нельзя")
# 7. Деление на цело
    if choice == 7:
        if num2 != 0: # Проверка деления на ноль
            result = num1 // num2
            print(f"Степень: {result}")
            if result > 12: # Доп. условие
                print("Внимание: Получится большая порция блюда!")
        else:
            print("Ошибка: на ноль делить нельзя")
    if 1 > choice > 7:
        print("Такого варианта нет. Попробуйте снова.")